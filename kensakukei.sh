#!/bin/bash

clear
echo "=============================================="
echo "何を検索したいですか"
echo "=============================================="
echo "特定のファイル　：　1     特定の文字列　：　2"
echo "=============================================="
read nyuuryoku

# 入力された値に応じて対応したシェルを実行する
case "$nyuuryoku" in
    1)
        echo "特定のファイルを検索する場合：find"
        ;;
    2)
        echo "ファイルから特定の文字列を検索する場合：grep"
        ;;
    *)
        echo "エラー: 1から2の数値を入力してください。"
        exit 1
        ;;
esac
